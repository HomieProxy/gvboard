func TestSchemaGeneratesForBothDialects(t *testing.T) {
	seen := map[string]bool{}
	for _, tb := range Schema() {
		if seen[tb.Name] {
			t.Errorf("表 %s 重复定义", tb.Name)
		}
		seen[tb.Name] = true
		for _, d := range []string{config.DriverMySQL, config.DriverPostgres} {
			stmts, err := CreateTableSQL(d, tb)
			if err != nil {
				t.Errorf("%s %s: %v", d, tb.Name, err)
				continue
			}
			if len(stmts) == 0 || !strings.HasPrefix(stmts[0], "CREATE TABLE IF NOT EXISTS") {
				t.Errorf("%s %s 建表语句不正确", d, tb.Name)
			}
			for _, c := range tb.Columns {
				if _, err := AddColumnSQL(d, tb.Name, c); err != nil {
					t.Errorf("%s %s.%s: %v", d, tb.Name, c.Name, err)
				}
			}
		}
	}

	// 原项目全部业务表（install.sql 中除 Laravel 的 failed_jobs 外）与 Gvboard 新增表
	required := []string{
		"v2_commission_log", "v2_coupon", "v2_giftcard", "v2_invite_code", "v2_knowledge", "v2_log",
		"v2_mail_log", "v2_notice", "v2_order", "v2_payment", "v2_plan", "v2_server_group",
		"v2_server_tuic", "v2_server_hysteria", "v2_server_route", "v2_server_shadowsocks",
		"v2_server_trojan", "v2_server_vless", "v2_server_vmess", "v2_server_anytls", "v2_server_v2node",
		"v2_stat", "v2_stat_server", "v2_stat_user", "v2_ticket", "v2_ticket_message", "v2_user",
		"v2_subscription", "v2_settings", "v2_plugin", "v2_plugin_kv",
		"v2_subscribe_rule", "v2_subscribe_log", "v2_user_telegram", "v2_order_adjustment",
	}
	for _, n := range required {
		if !seen[n] {
			t.Errorf("缺少表定义 %s", n)
		}
	}
}

func findTable(name string) Table {
	for _, t := range Schema() {
		if t.Name == name {
			return t
		}
	}
	panic("表不存在: " + name)
}

func TestMySQLDDL(t *testing.T) {
	stmts, _ := CreateTableSQL(config.DriverMySQL, findTable("v2_user"))
	s := stmts[0]
	for _, want := range []string{
		"`id` int NOT NULL AUTO_INCREMENT",
		"`email` varchar(64) NOT NULL",
		"`expired_at` bigint NULL DEFAULT '0'",
		"`remind_expire` tinyint NULL DEFAULT '1'",
		"UNIQUE KEY `email` (`email`)",
		"UNIQUE KEY `token` (`token`)",
		"PRIMARY KEY (`id`)",
		"utf8mb4",
	} {
		if !strings.Contains(s, want) {
			t.Errorf("MySQL v2_user 建表语句缺少 %q\n%s", want, s)
		}
	}
	stmts, _ = CreateTableSQL(config.DriverMySQL, findTable("v2_server_v2node"))
	if !strings.Contains(stmts[0], "`listen_ip` varchar(255) NOT NULL DEFAULT '0.0.0.0'") {
		t.Errorf("字符串默认值不正确\n%s", stmts[0])
	}
	stmts, _ = CreateTableSQL(config.DriverMySQL, findTable("v2_server_vmess"))
	if !strings.Contains(stmts[0], "`networkSettings` text NULL") {
		t.Errorf("驼峰列名应保持原样\n%s", stmts[0])
	}
}

func TestPostgresDDL(t *testing.T) {
	stmts, _ := CreateTableSQL(config.DriverPostgres, findTable("v2_user"))
	all := strings.Join(stmts, "\n")
	for _, want := range []string{
		`"id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`,
		`"token" varchar(32) NOT NULL`, // char 转为 varchar，避免末尾补空格
		`"banned" smallint NOT NULL DEFAULT 0`,
		`CREATE UNIQUE INDEX IF NOT EXISTS "v2_user_email" ON "v2_user" ("email")`,
	} {
		if !strings.Contains(all, want) {
			t.Errorf("PostgreSQL v2_user 语句缺少 %q\n%s", want, all)
		}
	}
	stmts, _ = CreateTableSQL(config.DriverPostgres, findTable("v2_server_vless"))
	if !strings.Contains(stmts[0], `"port" varchar(11) NOT NULL`) {
		t.Errorf("vless 端口在 PostgreSQL 中应为 varchar，以支持端口段\n%s", stmts[0])
	}
	stmts, _ = CreateTableSQL(config.DriverPostgres, findTable("v2_payment"))
	if !strings.Contains(stmts[0], `"handling_fee_percent" numeric(5,2) NULL`) {
		t.Errorf("decimal 应转为 numeric\n%s", stmts[0])
	}
}

func TestAddColumnForExistingRows(t *testing.T) {
	// 向已有数据的表追加非空无默认值的列时，数值列补默认 0，文本列改为可空
	s, _ := AddColumnSQL(config.DriverMySQL, "v2_x", col("n", "int"))
	if !strings.Contains(s, "`n` int NOT NULL DEFAULT '0'") {
		t.Errorf("数值列: %s", s)
	}
	s, _ = AddColumnSQL(config.DriverPostgres, "v2_x", col("s", "varchar(10)"))
	if !strings.Contains(s, `"s" varchar(10) NULL`) {
		t.Errorf("字符串列: %s", s)
	}
	s, _ = AddColumnSQL(config.DriverMySQL, "v2_x", col("t", "text"))
	if !strings.Contains(s, "`t` text NULL") || strings.Contains(s, "DEFAULT") {
		t.Errorf("text 列不能带默认值: %s", s)
	}
}

func TestStepsOrderStable(t *testing.T) {
	steps := Steps()
	seen := map[string]bool{}
	prev := ""
	for _, s := range steps {
		if seen[s.ID] {
			t.Errorf("迁移步骤 ID 重复: %s", s.ID)
		}
		seen[s.ID] = true
		if s.ID <= prev {
			t.Errorf("迁移步骤必须按 ID 升序追加: %s 在 %s 之后", s.ID, prev)
		}
		prev = s.ID
	}
}
